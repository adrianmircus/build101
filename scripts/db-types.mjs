// Regenerates lib/server/db/types.ts from the local database (`npm run db:start` first).
// A script and not a shell redirect because the file has to start with `import "server-only"`
// (an ESLint rule for everything under lib/server) and has to be byte-identical on Windows and
// Linux: CI fails when `git diff` finds differences after regenerating.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const TARGET = "lib/server/db/types.ts";
const HEADER = '// Generated by `npm run db:types` from the local database. Do not edit by hand.\nimport "server-only";\n\n';

const generated = execSync("npx supabase gen types typescript --local --schema public", {
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
});

writeFileSync(TARGET, HEADER + generated.replaceAll("\r\n", "\n"));
console.log(`Escribí ${TARGET}`);
